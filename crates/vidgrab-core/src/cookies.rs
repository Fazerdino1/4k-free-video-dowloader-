//! Netscape HTTP Cookie File formatter and parser for `yt-dlp --cookies`.
//!
//! Writes cookie files with strict `0600` Unix permissions so session tokens
//! exported from the built-in WebKitGTK browser remain private to the current user.

use crate::error::CoreResult;
use std::fs::{self, OpenOptions};
use std::io::Write;
use std::os::unix::fs::OpenOptionsExt;
use std::os::unix::fs::PermissionsExt;
use std::path::Path;
use vidgrab_shared::CookieEntry;

const NETSCAPE_HEADER: &str = "# Netscape HTTP Cookie File\n# https://curl.se/docs/http-cookies.html\n# This file was generated by 4k free video dowloader. Edit at your own risk.\n\n";

/// Formats a slice of [`CookieEntry`] items into the standard Netscape 7-column tab-separated format.
pub fn format_netscape_cookies(cookies: &[CookieEntry]) -> String {
    let mut out = String::from(NETSCAPE_HEADER);
    for c in cookies {
        let domain = if c.include_subdomains && !c.domain.starts_with('.') {
            format!(".{}", c.domain)
        } else {
            c.domain.clone()
        };
        let flag = if domain.starts_with('.') {
            "TRUE"
        } else {
            "FALSE"
        };
        let secure = if c.secure { "TRUE" } else { "FALSE" };
        let path = if c.path.is_empty() { "/" } else { &c.path };
        let name = c.name.replace(['\t', '\n', '\r'], "");
        let value = c.value.replace(['\t', '\n', '\r'], "");

        out.push_str(&format!(
            "{domain}\t{flag}\t{path}\t{secure}\t{}\t{name}\t{value}\n",
            c.expires.max(0)
        ));
    }
    out
}

/// Writes `cookies` in Netscape format to `path` with strict `0600` (`rw-------`) Unix permissions.
pub fn write_netscape_cookies_file(path: &Path, cookies: &[CookieEntry]) -> CoreResult<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    let content = format_netscape_cookies(cookies);

    let mut file = OpenOptions::new()
        .create(true)
        .write(true)
        .truncate(true)
        .mode(0o600)
        .open(path)?;

    // Explicitly enforce 0600 even if the file already existed with broader permissions
    let mut perms = file.metadata()?.permissions();
    perms.set_mode(0o600);
    file.set_permissions(perms)?;

    file.write_all(content.as_bytes())?;
    file.sync_all()?;
    Ok(())
}

/// Parses a Netscape cookie file back into [`CookieEntry`] structs.
pub fn parse_netscape_cookies(content: &str) -> Vec<CookieEntry> {
    let mut list = Vec::new();
    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || (trimmed.starts_with('#') && !trimmed.starts_with("#HttpOnly_")) {
            continue;
        }
        let cleaned = trimmed.strip_prefix("#HttpOnly_").unwrap_or(trimmed);
        let cols: Vec<&str> = cleaned.split('\t').collect();
        if cols.len() >= 7 {
            let domain = cols[0].to_string();
            let include_subdomains = cols[1].eq_ignore_ascii_case("TRUE");
            let path = cols[2].to_string();
            let secure = cols[3].eq_ignore_ascii_case("TRUE");
            let expires = cols[4].parse::<i64>().unwrap_or(0);
            let name = cols[5].to_string();
            let value = cols[6].to_string();
            list.push(CookieEntry {
                domain,
                include_subdomains,
                path,
                secure,
                expires,
                name,
                value,
            });
        }
    }
    list
}
